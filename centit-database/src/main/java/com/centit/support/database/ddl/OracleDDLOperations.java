package com.centit.support.database.ddl;

import com.centit.support.algorithm.GeneralAlgorithm;
import com.centit.support.database.metadata.TableField;
import com.centit.support.database.utils.FieldType;
import com.centit.support.database.utils.QueryUtils;
import org.apache.commons.lang3.StringUtils;

import java.sql.Connection;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.List;

public class OracleDDLOperations extends GeneralDDLOperations {

    public OracleDDLOperations() {

    }

    public OracleDDLOperations(Connection conn) {
        super(conn);
    }

    @Override
    protected void appendColumnTypeSQL(final TableField field, StringBuilder sbCreate) {
        if (FieldType.IDENTITY.equalsIgnoreCase(field.getFieldType())) {
            if (conn != null) {
                try {
                    if (!StringUtils.containsIgnoreCase(conn.getMetaData().getDatabaseProductName(), "Oracle")) {
                        throw new UnsupportedOperationException("Oracle identity 语法仅支持 Oracle 数据库");
                    }
                    if (conn.getMetaData().getDatabaseMajorVersion() < 12) {
                        throw new UnsupportedOperationException("Oracle identity 列需要 12c 或更新版本");
                    }
                } catch (SQLException e) {
                    throw new IllegalStateException("无法获取 Oracle 数据库版本", e);
                }
            }
            appendColumnDataTypeSQL(field, sbCreate);
            sbCreate.append(" GENERATED BY DEFAULT AS IDENTITY");
        } else {
            super.appendColumnDataTypeSQL(field, sbCreate);
        }
    }

    @Override
    protected void appendColumnDataTypeSQL(final TableField field, StringBuilder sbCreate) {
        if (FieldType.IDENTITY.equalsIgnoreCase(field.getFieldType())) {
            if (StringUtils.equalsAnyIgnoreCase(field.getColumnType(), "NUMBER", "NUMERIC", "DECIMAL") && field.getMaxLength() <= 0) {
                sbCreate.append(field.getColumnType()).append("(18,0)");
            } else if (StringUtils.equalsAnyIgnoreCase(field.getColumnType(), "NUMBER", "NUMERIC", "DECIMAL", "INTEGER", "INT", "SMALLINT")) {
                super.appendColumnDataTypeSQL(field, sbCreate);
            } else {
                sbCreate.append("number(18,0)");
            }
        } else {
            super.appendColumnDataTypeSQL(field, sbCreate);
        }
    }

    @Override
    public String makeCreateSequenceSql(final String sequenceName) {
        return "create sequence " + QueryUtils.trimSqlIdentifier(sequenceName);
    }

    @Override
    public List<String> makeModifyColumnSqls(final String tableCode, final TableField oldColumn, final TableField column) {
        validateIdentityChange(oldColumn, column);
        List<String> sqlList = new ArrayList<>();
        boolean typeChanged = !StringUtils.equalsIgnoreCase(oldColumn.getColumnType(), column.getColumnType())
            || !GeneralAlgorithm.equals(oldColumn.getMaxLength(), column.getMaxLength())
            || !GeneralAlgorithm.equals(oldColumn.getScale(), column.getScale());
        boolean nullableChanged = !FieldType.IDENTITY.equalsIgnoreCase(column.getFieldType())
            && oldColumn.isMandatory() != column.isMandatory();
        boolean defaultChanged = !StringUtils.equals(StringUtils.trimToEmpty(oldColumn.getDefaultValue()),
            StringUtils.trimToEmpty(column.getDefaultValue()));
        if (typeChanged || nullableChanged || defaultChanged) {
            StringBuilder sbsql = new StringBuilder("alter table ").append(tableCode)
                .append(" modify ").append(column.getColumnName()).append(" ");
            if (typeChanged) {
                appendColumnDataTypeSQL(column, sbsql);
            }
            if (defaultChanged) {
                sbsql.append(" default ").append(StringUtils.isBlank(column.getDefaultValue()) ? "null" : column.getDefaultValue());
            }
            if (nullableChanged) {
                sbsql.append(column.isMandatory() ? " not null" : " null");
            }
            sqlList.add(sbsql.toString());
        }
        if (!StringUtils.equals(StringUtils.defaultString(oldColumn.getFieldLabelName()), StringUtils.defaultString(column.getFieldLabelName()))) {
            sqlList.add("comment on column " + tableCode + "." + column.getColumnName() + " is '"
                + StringUtils.defaultString(column.getFieldLabelName()).replace("'", "''") + "'");
        }
        return sqlList;
    }

    @Override
    public String makeAddColumnSql(final String tableCode, final TableField column) {
        StringBuilder sbsql = new StringBuilder("alter table ");
        sbsql.append(tableCode);
        sbsql.append(" add ");
        appendColumnSQL(column, sbsql);
        return sbsql.toString();
    }

}
