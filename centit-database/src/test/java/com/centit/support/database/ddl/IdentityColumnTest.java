package com.centit.support.database.ddl;

import com.centit.support.database.metadata.JdbcMetadata;
import com.centit.support.database.metadata.SimpleTableField;
import com.centit.support.database.metadata.SimpleTableInfo;
import com.centit.support.database.utils.FieldType;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.Statement;

import static org.junit.jupiter.api.Assertions.*;

class IdentityColumnTest {
    private SimpleTableField identity() {
        SimpleTableField field = new SimpleTableField();
        field.setColumnName("ID");
        field.setColumnType("BIGINT");
        field.setFieldType(FieldType.IDENTITY);
        field.setPrimaryKey(true);
        return field;
    }

    @Test
    void generatesIdentityForEachDialect() {
        GeneralDDLOperations[] dialects = {new MySqlDDLOperations(), new SqlSvrDDLOperations(),
            new DB2DDLOperations(), new PostgreSqlDDLOperations(), new OracleDDLOperations(),
            new H2DDLOperations(), new SqliteDDLOperations()};
        String[] types = {"bigint AUTO_INCREMENT", "bigint identity(1,1)",
            "INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1, INCREMENT BY 1)", "SERIAL",
            "number(18,0) GENERATED BY DEFAULT AS IDENTITY", "bigint GENERATED BY DEFAULT AS IDENTITY", "INTEGER"};
        for (int i = 0; i < dialects.length; i++) {
            StringBuilder sql = new StringBuilder();
            dialects[i].appendColumnTypeSQL(identity(), sql);
            assertEquals(types[i], sql.toString());
        }
        SimpleTableInfo table = new SimpleTableInfo("T_IDENTITY");
        table.addColumn(identity());
        assertTrue(new SqliteDDLOperations().makeCreateTableSql(table).contains("primary key AUTOINCREMENT"));
        assertEquals(FieldType.IDENTITY, FieldType.mapToFieldType("identity"));
        assertEquals(Long.class, FieldType.mapToJavaType(FieldType.IDENTITY));
    }

    @Test
    void createsAndReverseEngineersIdentityInH2() throws Exception {
        try (Connection conn = DriverManager.getConnection("jdbc:h2:mem:identity_test", "sa", "");
             Statement stmt = conn.createStatement()) {
            SimpleTableInfo table = new SimpleTableInfo("T_IDENTITY");
            table.addColumn(identity());
            H2DDLOperations ddl = new H2DDLOperations();
            stmt.execute(ddl.makeCreateTableSql(table));
            stmt.execute("insert into T_IDENTITY default values");
            stmt.execute("insert into T_IDENTITY default values");
            try (ResultSet rs = stmt.executeQuery("select ID from T_IDENTITY order by ID")) {
                assertTrue(rs.next());
                assertEquals(1, rs.getLong(1));
                assertTrue(rs.next());
                assertEquals(2, rs.getLong(1));
            }
            JdbcMetadata metadata = new JdbcMetadata();
            metadata.setDBConfig(conn);
            SimpleTableInfo reverse = metadata.getTableMetadata("T_IDENTITY");
            assertEquals(FieldType.IDENTITY, reverse.getColumns().get(0).getFieldType());
            assertEquals("BIGINT", reverse.getColumns().get(0).getColumnType());
            assertNull(reverse.getColumns().get(0).getDefaultValue());
            reverse.setTableName("T_IDENTITY_COPY");
            stmt.execute(ddl.makeCreateTableSql(reverse));
            stmt.execute("insert into T_IDENTITY_COPY default values");
        }
    }
}
