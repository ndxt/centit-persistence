package com.centit.support.database.metadata;

import com.centit.support.database.utils.FieldType;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.Map;
import java.util.UUID;
import java.util.stream.Collectors;

import static org.junit.jupiter.api.Assertions.*;

class JdbcMetadataTest {
    private Connection connection;
    private JdbcMetadata metadata;

    @BeforeEach
    void openDatabase() throws SQLException {
        connection = DriverManager.getConnection("jdbc:h2:mem:metadata_" + UUID.randomUUID(), "sa", "");
        metadata = new JdbcMetadata();
        metadata.setDBConfig(connection);
    }

    @AfterEach
    void closeDatabase() throws SQLException {
        connection.close();
    }

    @Test
    void listsBaseTablesAndViewColumns() throws SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.execute("create table T_BASE (ID bigint primary key, NAME varchar(20))");
            statement.execute("create view V_BASE as select ID, NAME from T_BASE");
        }
        var tables = metadata.listTables(true, new String[]{"t_base", "v_base"});
        assertEquals(2, tables.size());
        var byName = tables.stream().collect(Collectors.toMap(SimpleTableInfo::getTableName, table -> table));
        assertEquals("T", byName.get("T_BASE").getTableType());
        assertEquals("V", byName.get("V_BASE").getTableType());
        assertEquals(2, byName.get("V_BASE").getColumns().size());
        assertEquals("PUBLIC", byName.get("T_BASE").getSchema());
        assertEquals("V", metadata.getTableMetadata("V_BASE").getTableType());
        assertNull(metadata.getTableMetadata("NO_SUCH_TABLE"));
    }

    @Test
    void preservesExactTableSchemaCommentsDefaultsAndIdentity() throws SQLException {
        String comment = "table comment ".repeat(8);
        try (Statement statement = connection.createStatement()) {
            statement.execute("create schema \"s_a\"");
            statement.execute("create schema \"sXa\"");
            statement.execute("create table \"s_a\".T_A (ID bigint generated by default as identity primary key, N integer default 7 not null)");
            statement.execute("create table \"s_a\".TXA (OTHER_ID bigint)");
            statement.execute("create table \"sXa\".T_A (WRONG_SCHEMA bigint)");
            statement.execute("create table \"s_a\".\"T%P\" (EXACT_COL bigint)");
            statement.execute("create table \"s_a\".TXP (OTHER_COL bigint)");
            statement.execute("comment on table \"s_a\".T_A is '" + comment + "'");
            statement.execute("comment on column \"s_a\".T_A.N is 'column comment'");
        }
        metadata.setDBSchema("s_a");
        SimpleTableInfo table = metadata.getTableMetadata("T_A");
        assertEquals("s_a", table.getSchema());
        assertEquals(comment, table.getTableComment());
        assertEquals(comment.substring(0, 80), table.getTableLabelName());
        assertEquals(2, table.getColumns().size());
        assertEquals(FieldType.IDENTITY, table.findFieldByColumn("ID").getFieldType());
        assertNull(table.findFieldByColumn("ID").getDefaultValue());
        assertEquals("7", table.findFieldByColumn("N").getDefaultValue());
        assertTrue(table.findFieldByColumn("N").isMandatory());
        assertEquals("column comment", table.findFieldByColumn("N").getColumnComment());
        assertEquals("EXACT_COL", metadata.getTableMetadata("T%P").getColumns().get(0).getColumnName());
        var filtered = metadata.listTables(true, new String[]{"T_A"});
        assertEquals(1, filtered.size());
        assertEquals(2, filtered.get(0).getColumns().size());
    }

    @Test
    void retainsSeparateForeignKeysAndParentChildColumnNames() throws SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.execute("create table PARENT_TABLE (ID bigint primary key)");
            statement.execute("create table CHILD_TABLE (ID bigint primary key, P1 bigint, P2 bigint, "
                + "constraint FK_ONE foreign key (P1) references PARENT_TABLE(ID), "
                + "constraint FK_TWO foreign key (P2) references PARENT_TABLE(ID))");
        }
        var references = metadata.getTableMetadata("PARENT_TABLE").getReferences();
        assertEquals(2, references.size());
        var byName = references.stream().collect(Collectors.toMap(SimpleTableReference::getReferenceCode, ref -> ref));
        assertEquals(Map.of("ID", "P1"), byName.get("FK_ONE").getReferenceColumns());
        assertEquals(Map.of("ID", "P2"), byName.get("FK_TWO").getReferenceColumns());
        assertEquals("CHILD_TABLE", byName.get("FK_ONE").getTableName());
    }

    @Test
    void keepsSameNamedForeignKeysInDifferentSchemas() throws SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.execute("create schema S_ONE");
            statement.execute("create schema S_TWO");
            statement.execute("create table PARENT_SCOPE (ID bigint primary key)");
            statement.execute("create table S_ONE.SAME_CHILD (LEFT_ID bigint, "
                + "constraint FK_SHARED foreign key (LEFT_ID) references PUBLIC.PARENT_SCOPE(ID))");
            statement.execute("create table S_TWO.SAME_CHILD (RIGHT_ID bigint, "
                + "constraint FK_SHARED foreign key (RIGHT_ID) references PUBLIC.PARENT_SCOPE(ID))");
        }
        var references = metadata.getTableMetadata("PARENT_SCOPE").getReferences();
        assertEquals(2, references.size());
        assertEquals(java.util.Set.of(Map.of("ID", "LEFT_ID"), Map.of("ID", "RIGHT_ID")),
            references.stream().map(SimpleTableReference::getReferenceColumns).collect(Collectors.toSet()));
    }

    @Test
    void preservesCompositePrimaryKeyOrder() throws SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.execute("create table KEY_TABLE (A integer, B integer, primary key (B, A))");
        }
        SimpleTableInfo table = metadata.getTableMetadata("KEY_TABLE");
        assertEquals(java.util.List.of("B", "A"), table.getPkFields().stream().map(TableField::getColumnName).toList());
        assertEquals(1, table.findFieldByColumn("B").getPrimaryKeyOrder());
        assertEquals(2, table.findFieldByColumn("A").getPrimaryKeyOrder());
    }

    @Test
    void propagatesDatabaseErrorsAndRejectsEmptyNames() throws SQLException {
        assertThrows(IllegalArgumentException.class, () -> metadata.getTableMetadata(" "));
        assertThrows(IllegalArgumentException.class, () -> metadata.listTables(false, new String[]{null}));
        connection.close();
        var failure = assertThrows(IllegalStateException.class, () -> metadata.getTableMetadata("T_ANY"));
        assertInstanceOf(SQLException.class, failure.getCause());
        assertThrows(IllegalStateException.class, () -> metadata.listTables(true, null));
    }
}
