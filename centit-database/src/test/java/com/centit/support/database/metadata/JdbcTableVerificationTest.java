package com.centit.support.database.metadata;

import com.alibaba.fastjson2.JSONArray;
import com.alibaba.fastjson2.JSONObject;
import com.centit.support.database.utils.FieldType;
import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.Test;

import java.sql.*;
import java.util.List;

class JdbcTableVerificationTest {
    @Test
    void identityTypeMatchesItsNativeAutoIncrementEvidence() throws Exception {
        try (Connection connection = DriverManager.getConnection("jdbc:h2:mem:strict_generated_identity");
             Statement statement = connection.createStatement()) {
            statement.execute("create table GENERATED_KEYS (ID bigint generated by default as identity primary key, LABEL varchar(20))");
            statement.execute("insert into GENERATED_KEYS(LABEL) values('first'), ('second')");
            JSONObject id = column(JdbcTableVerification.read(connection, "PUBLIC", "GENERATED_KEYS"), "ID");
            Assertions.assertEquals("YES", id.getString("autoIncrement"));
            Assertions.assertEquals(FieldType.IDENTITY, id.getString("fieldType"));
            Assertions.assertTrue(id.getBooleanValue("mandatory"));
            Assertions.assertEquals(FieldType.STRING,
                    column(JdbcTableVerification.read(connection, "PUBLIC", "GENERATED_KEYS"), "LABEL").getString("fieldType"));
            try (ResultSet rows = statement.executeQuery("select ID from GENERATED_KEYS order by ID")) {
                Assertions.assertTrue(rows.next()); Assertions.assertEquals(1, rows.getLong(1));
                Assertions.assertTrue(rows.next()); Assertions.assertEquals(2, rows.getLong(1)); Assertions.assertFalse(rows.next());
            }
        }
    }

    @Test
    void readsCompositeKeysIndexesTwoReferencesAndExactDefaults() throws Exception {
        try (Connection connection = DriverManager.getConnection("jdbc:h2:mem:strict_structure");
             Statement statement = connection.createStatement()) {
            statement.execute("create table PARENT (B int, A int, primary key (B,A))");
            statement.execute("create table CHILD (ID int primary key, B1 int, A1 int, B2 int, A2 int, "
                    + "AMOUNT decimal(12,3) default 0 not null, LABEL varchar(25) default '', "
                    + "constraint FK_FIRST foreign key (B1,A1) references PARENT(B,A), "
                    + "constraint FK_SECOND foreign key (B2,A2) references PARENT(B,A))");
            statement.execute("create unique index UQ_CHILD_PAIR on CHILD (A1 desc,B1 asc)");
            JSONObject child = JdbcTableVerification.read(connection, "PUBLIC", "CHILD");
            Assertions.assertEquals("jdbc-verification", child.getString("source"));
            Assertions.assertEquals(7, child.getJSONArray("columns").size());
            JSONObject amount = column(child, "AMOUNT");
            Assertions.assertEquals(12, amount.getIntValue("maxLength"));
            Assertions.assertEquals(3, amount.getIntValue("scale"));
            Assertions.assertTrue(amount.getBooleanValue("mandatory"));
            Assertions.assertEquals("0", amount.getJSONObject("defaultDefinition").getString("expression"));
            Assertions.assertEquals("''", column(child, "LABEL").getJSONObject("defaultDefinition").getString("expression"));
            Assertions.assertFalse(column(child, "ID").getJSONObject("defaultDefinition").getBooleanValue("present"));
            List<JSONObject> uniqueIndex = child.getJSONArray("indexes").toJavaList(JSONObject.class)
                    .stream().filter(row -> "UQ_CHILD_PAIR".equals(row.getString("name"))).toList();
            Assertions.assertEquals(List.of("A1", "B1"), uniqueIndex.stream().map(row -> row.getString("columnName")).toList());
            Assertions.assertEquals(List.of("D", "A"), uniqueIndex.stream().map(row -> row.getString("direction")).toList());
            Assertions.assertTrue(uniqueIndex.stream().allMatch(row -> row.getBooleanValue("unique")));
            Assertions.assertEquals(4, child.getJSONArray("importedKeys").size());
            Assertions.assertEquals(List.of("FK_FIRST", "FK_FIRST", "FK_SECOND", "FK_SECOND"),
                    child.getJSONArray("importedKeys").toJavaList(JSONObject.class).stream().map(row -> row.getString("name")).toList());
            JSONObject parent = JdbcTableVerification.read(connection, "PUBLIC", "PARENT");
            Assertions.assertEquals(List.of("B", "A"), parent.getJSONArray("primaryKeys")
                    .toJavaList(JSONObject.class).stream().map(row -> row.getString("columnName")).toList());
            Assertions.assertEquals(4, parent.getJSONArray("exportedKeys").size());
            Assertions.assertEquals(0, parent.getJSONArray("importedKeys").size());
            Assertions.assertEquals(JSONArray.of("check constraints, triggers and runtime behavior"), parent.getJSONArray("unverified"));
            // The reader performed no row mutation.
            try (ResultSet rows = statement.executeQuery("select count(*) from CHILD")) {
                rows.next();
                Assertions.assertEquals(0, rows.getInt(1));
            }
        }
    }

    @Test
    void resolvesDriverIdentifierCaseWithoutConfusingPatternsOrQuotedTables() throws Exception {
        try (Connection connection = DriverManager.getConnection("jdbc:h2:mem:strict_identity");
             Statement statement = connection.createStatement()) {
            statement.execute("create table A_B(ID int)");
            statement.execute("create table AXB(OTHER int)");
            statement.execute("create table \"a%b\" (\"value\" int)");
            JSONObject table = JdbcTableVerification.read(connection, "PUBLIC", "A_B");
            Assertions.assertEquals("ID", table.getJSONArray("columns").getJSONObject(0).getString("columnName"));
            Assertions.assertEquals("a%b", JdbcTableVerification.read(connection, "PUBLIC", "a%b").getString("tableName"));
            JSONObject folded = JdbcTableVerification.read(connection, "PUBLIC", "a_b");
            Assertions.assertTrue(JdbcTableVerification.tableExists(connection, "PUBLIC", "a_b"));
            Assertions.assertFalse(JdbcTableVerification.tableExists(connection, "PUBLIC", "A%B"));
            Assertions.assertFalse(JdbcTableVerification.tableExists(connection, "PUBLIC", "MISSING"));
            Assertions.assertEquals("A_B", folded.getString("tableName"));
            Assertions.assertEquals("a_b", folded.getString("requestedTableName"));
            Assertions.assertEquals("upper", folded.getString("unquotedIdentifierCase"));
            Assertions.assertEquals("unquoted-case-fold", folded.getString("identityResolution"));
            Assertions.assertThrows(SQLException.class, () -> JdbcTableVerification.read(connection, "PUBLIC", "MISSING"));
            statement.execute("create table \"a_b\" (QUOTED_ID int)");
            Assertions.assertThrows(SQLException.class, () -> JdbcTableVerification.tableExists(connection, "PUBLIC", "a_b"));
            Assertions.assertThrows(SQLException.class, () -> JdbcTableVerification.read(connection, "PUBLIC", "a_b"),
                    "When exact and folded identities both exist, binding metadata must disambiguate them");
            statement.execute("create table \"MixedCase\" (QUOTED_ID int)");
            Assertions.assertEquals("exact", JdbcTableVerification.read(connection, "PUBLIC", "MixedCase")
                    .getString("identityResolution"));
            Assertions.assertThrows(SQLException.class, () -> JdbcTableVerification.read(connection, "PUBLIC", "mixedcase"));
            statement.execute("create schema OTHER_SCHEMA");
            statement.execute("create table OTHER_SCHEMA.A_B(ID int)");
            Assertions.assertThrows(SQLException.class, () -> JdbcTableVerification.read(connection, null, "A_B"));
        }
    }

    @Test
    void followsLowerCaseStorageOnlyWhenDeclaredByTheDriver() throws Exception {
        try (Connection connection = DriverManager.getConnection("jdbc:h2:mem:lower_identifiers;DATABASE_TO_LOWER=TRUE");
             Statement statement = connection.createStatement()) {
            statement.execute("create table EXAMPLE(ID int)");
            JSONObject result = JdbcTableVerification.read(connection, "public", "EXAMPLE");
            Assertions.assertEquals("example", result.getString("tableName"));
            Assertions.assertEquals("lower", result.getString("unquotedIdentifierCase"));
            Assertions.assertEquals("id", column(result, "id").getString("columnName"));
        }
    }

    private JSONObject column(JSONObject table, String name) {
        return table.getJSONArray("columns").toJavaList(JSONObject.class).stream()
                .filter(row -> name.equals(row.getString("columnName"))).findFirst().orElseThrow();
    }
}
